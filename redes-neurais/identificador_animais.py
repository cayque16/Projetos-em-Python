probabilities = softmax(z2)

classes = ["Dog", "Cat", "Rabbit"]

print("\nClassification result:")

for name, probability, in zip(classes, probabilities[0]):
  print(f"{name}: {probability * 100:.2f}%")

predicted_class = np.argmax(probabilities)

print(f"\nPredicted animal: {classes[predicted_class]}")