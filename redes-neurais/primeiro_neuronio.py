import numpy as np

x = np.array([50, 60, 70, 80, 100], dtype=float)
y = np.array([150_000, 180_000, 210_000, 240_000, 300_000], dtype=float)

x = x / np.max(x)
y = y / np.max(y)

weight, bias = 0.0, 0.0

learning_rate = 0.1
epochs = 2000

for epoch in range(epochs):

    # Forward propagation: make predictions
    predictions = weight * x + bias

    # Calculate the error
    errors = predictions - y

    # Mean Squared Error (MSE)
    loss = np.mean(errors ** 2)

    # Calculate gradients
    d_weight = 2 * np.mean(errors * x)
    d_bias = 2 * np.mean(errors)

    # Update the parameters
    weight -= learning_rate * d_weight
    bias -= learning_rate * d_bias

    # Display training progress
    if epoch % 200 == 0:
        print(f"Epoch: {epoch:4d} | Loss: {loss:.6f}")

# 5. Display the learned parameters

print("\nTraining completed!")
print(f"Weight: {weight:.4f}")
print(f"Bias: {bias:.4f}")

# 6. Test the neuron with a new house
house_size = 100

normalized_size = house_size / 100

predicted_price = (weight * normalized_size + bias) * 300_000

print(f"\nHouse size: {house_size} m²")
print(f"Predicted price: R$ {predicted_price:,.2f}")